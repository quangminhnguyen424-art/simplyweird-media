"""Simply Weird motion-graphics builder (Remotion). Default format for daily videos.

An episode is a folder motion/src/episodes/<slug>/ with:
  script.json  [{"id": "hook", "say": "..."}, ...]   (one scene per line, ids match Scenes.tsx)
  Scenes.tsx   exports title, segs (= timing.json), scenes {id: {C, hue}}  -- built from ../../kit
  timing.json  written by `tts`

Usage (from repo root):
  python3 motion/build.py tts      SLUG      # Kokoro narration -> out/motion/SLUG/*.wav + timing.json
  python3 motion/build.py register           # rewrite src/registry.ts from episode folders
  python3 motion/build.py stills   SLUG      # one PNG per scene (mid-scene) into out/motion/SLUG/stills
  python3 motion/build.py render   SLUG      # silent render + narration/SFX/music mix -> out/SLUG.mp4
  python3 motion/build.py all      SLUG      # tts + register + render
Needs: npm install inside motion/ once per fresh session; Chrome at /usr/bin/google-chrome (or set CHROME).
"""
import json, os, subprocess, sys
import numpy as np
import soundfile as sf

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "engine"))
FPS, PAD, LEAD, TAIL = 30, 0.35, 8, 20  # must match src/kit.tsx
CHROME = os.environ.get("CHROME", "/usr/bin/google-chrome")
TTS_DIR = os.environ.get("KOKORO_DIR", "/home/claude/tts")


def epdir(slug): return os.path.join(HERE, "src", "episodes", slug)
def work(slug):
    d = os.path.join(ROOT, "out", "motion", slug); os.makedirs(d, exist_ok=True); return d
def comp_id(slug): return "ep" + slug.replace("-", "")


def tts(slug, voice="am_michael", speed=1.05):
    from kokoro_onnx import Kokoro
    k = Kokoro(os.path.join(TTS_DIR, "kokoro-v1.0.onnx"), os.path.join(TTS_DIR, "voices-v1.0.bin"))
    script = json.load(open(os.path.join(epdir(slug), "script.json")))
    out = []
    for s in script:
        f = os.path.join(work(slug), s["id"] + ".wav")
        if not os.path.exists(f):
            a, sr = k.create(s["say"], voice=voice, speed=speed, lang="en-us")
            a = np.asarray(a, dtype=np.float32)
            idx = np.where(np.abs(a) > 0.01)[0]
            if len(idx): a = a[max(0, idx[0] - int(0.02 * sr)): idx[-1] + int(0.05 * sr)]
            sf.write(f, a, sr)
        a, sr = sf.read(f, dtype="float32")
        out.append({"id": s["id"], "say": s["say"], "dur": round(len(a) / sr, 3)})
    json.dump(out, open(os.path.join(epdir(slug), "timing.json"), "w"), indent=1)
    lens = [round((s["dur"] + PAD) * FPS) for s in out]
    print("tts ok:", len(out), "scenes,", round((sum(lens) + LEAD + TAIL) / FPS, 1), "s total")


def register():
    eps = sorted(d for d in os.listdir(os.path.join(HERE, "src", "episodes")) if os.path.exists(os.path.join(epdir(d), "Scenes.tsx")))
    lines = ["// Generated by motion/build.py register. Composition id = 'ep' + slug without dashes."]
    for e in eps: lines.append(f"import * as e{e.replace('-', '')} from './episodes/{e}/Scenes';")
    lines.append("export const EPISODES = {" + ", ".join(f"'{e}': e{e.replace('-', '')}" for e in eps) + "};")
    open(os.path.join(HERE, "src", "registry.ts"), "w").write("\n".join(lines) + "\n")
    print("registered:", eps)


def layout(slug):
    segs = json.load(open(os.path.join(epdir(slug), "timing.json")))
    lens = [round((s["dur"] + PAD) * FPS) for s in segs]
    starts = [LEAD + sum(lens[:i]) for i in range(len(lens))]
    return segs, lens, starts, starts[-1] + lens[-1] + TAIL


def remotion(*args):
    subprocess.run(["npx", "remotion", *args, f"--browser-executable={CHROME}"], cwd=HERE, check=True)


def stills(slug):
    segs, lens, starts, _ = layout(slug)
    d = os.path.join(work(slug), "stills"); os.makedirs(d, exist_ok=True)
    for s, l, st in zip(segs, lens, starts):
        remotion("still", "src/index.ts", comp_id(slug), os.path.join(d, f"{s['id']}.png"), f"--frame={st + int(l * 0.6)}", "--log=error")
    print("stills in", d)


def render(slug):
    from make import mix_audio
    segs, lens, starts, total = layout(slug)
    w = work(slug); silent = os.path.join(w, "silent.mp4")
    remotion("render", "src/index.ts", comp_id(slug), silent, "--concurrency=2", "--log=error")
    tl = []
    for s, st in zip(segs, starts):
        a, sr = sf.read(os.path.join(w, s["id"] + ".wav"), dtype="float32")
        tl.append(({}, st / FPS, st / FPS + len(a) / sr, a, sr))
    wav = mix_audio(w, tl, total / FPS, "mix", seed=sum(map(ord, slug)))
    out = os.path.join(ROOT, "out", slug + ".mp4")
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", silent, "-i", wav, "-map", "0:v", "-map", "1:a", "-c:v", "copy", "-c:a", "aac", "-b:a", "192k", "-shortest", "-movflags", "+faststart", out], check=True)
    print("done:", out, round(total / FPS, 1), "s")


if __name__ == "__main__":
    cmd = sys.argv[1]; slug = sys.argv[2] if len(sys.argv) > 2 else None
    if cmd == "tts": tts(slug)
    elif cmd == "register": register()
    elif cmd == "stills": stills(slug)
    elif cmd == "render": render(slug)
    elif cmd == "all": tts(slug); register(); render(slug)
